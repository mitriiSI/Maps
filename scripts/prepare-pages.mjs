import {
  cp,
  copyFile,
  mkdir,
  readFile,
  readdir,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const build = path.join(root, "dist");
const check = process.argv.includes("--check");
const index = await readFile(path.join(build, "index.html"), "utf8");
if (
  index.includes("/src/main.tsx") ||
  !/src="\.\/assets\/[^"\s]+\.js"/.test(index)
) {
  throw new Error(
    "The production index must reference compiled JavaScript under ./assets/.",
  );
}
async function files(dir, prefix = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  const result = [];
  for (const entry of entries) {
    const relative = path.join(prefix, entry.name);
    if (entry.isDirectory())
      result.push(...(await files(path.join(dir, entry.name), relative)));
    else result.push(relative);
  }
  return result.sort();
}
const builtFiles = await files(path.join(build, "assets"));
if (check) {
  try {
    if ((await readFile(path.join(root, "index.html"), "utf8")) !== index)
      throw new Error("Stale index.html");
    const published = await files(path.join(root, "assets"));
    if (JSON.stringify(published) !== JSON.stringify(builtFiles))
      throw new Error("Stale asset list");
    for (const file of builtFiles) {
      const a = await readFile(path.join(build, "assets", file));
      const b = await readFile(path.join(root, "assets", file));
      if (!a.equals(b)) throw new Error(`Stale asset: ${file}`);
    }
    if (
      !(await readFile(path.join(root, "favicon.svg"))).equals(
        await readFile(path.join(build, "favicon.svg")),
      )
    )
      throw new Error("Stale favicon");
    await stat(path.join(root, ".nojekyll"));
    console.log(
      "GitHub Pages index, favicon and all compiled assets match dist/.",
    );
  } catch (error) {
    throw new Error(
      `Run npm run build:pages and commit the generated files. ${error.message}`,
    );
  }
} else {
  // assets/ is generated by this script; authored assets belong in public/.
  await rm(path.join(root, "assets"), { recursive: true, force: true });
  await mkdir(path.join(root, "assets"), { recursive: true });
  await cp(path.join(build, "assets"), path.join(root, "assets"), {
    recursive: true,
  });
  await copyFile(path.join(build, "index.html"), path.join(root, "index.html"));
  await copyFile(
    path.join(build, "favicon.svg"),
    path.join(root, "favicon.svg"),
  );
  await writeFile(path.join(root, ".nojekyll"), "");
  console.log(
    `Prepared index.html and ${builtFiles.length} assets for the existing Pages branch source.`,
  );
}
